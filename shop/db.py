def database_url():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("Set DATABASE_URL to the Postgres database.")
    return url


def schema_for(path):
    if path is None or str(path) in ("", "public"):
        return "public"
    return "s_" + hashlib.sha256(str(path).encode("utf-8")).hexdigest()[:20]


class PgConn:
    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql, params=None):
        cursor = self._conn.cursor()
        cursor.execute(sql.replace("?", "%s"), params or ())
        return cursor

    def commit(self):
        self._conn.commit()

    def close(self):
        self._conn.close()


def connect(path=None):
    schema = schema_for(path)
    raw = psycopg.connect(database_url(), row_factory=dict_row)
    conn = PgConn(raw)
    conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
    conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
    conn.execute(f'SET search_path TO "{schema}", public')
    raw.commit()
    return conn


def reset_schema(conn, path):
    schema = schema_for(path)
    if schema == "public":
        for table in TABLES:
            conn.execute(f"DROP TABLE IF EXISTS {table} CASCADE")
        return
    conn.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
    conn.execute(f'CREATE SCHEMA "{schema}"')
    conn.execute(f'SET search_path TO "{schema}", public')


